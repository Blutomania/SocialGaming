// Generates server_py/rebus_data.py from lib/rebusData.js.
//
// Why generate rather than hand-port: the piece library and puzzle list are
// pure data, and a hand-typed second copy is a silent-divergence machine —
// one fixed emoji or corrected hint in the JS and the two backends quietly
// disagree about what the answer is. Only the two helper functions are
// written by hand in the Python module, because they're logic, not data.
//
// Run after editing lib/rebusData.js:  node scripts/build-rebus-py.mjs
// The output is committed, so nothing at runtime depends on this script.

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { REBUS_PIECES, REBUS_PUZZLES } from '../lib/rebusData.js';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const OUT = path.join(root, 'server_py/rebus_data.py');

const py = (v) => JSON.stringify(v, null, 4)
  .replace(/\btrue\b/g, 'True')
  .replace(/\bfalse\b/g, 'False')
  .replace(/\bnull\b/g, 'None');

const header = `# Generated by scripts/build-rebus-py.mjs — do not edit by hand.
# Source of truth: lib/rebusData.js. Re-run the script after changing it.
#
# A library of reusable PIECES plus PUZZLES that are nothing but lists of piece
# keys. The same atoms recur constantly, so keying them means one emoji choice
# per concept rather than one per puzzle. Nothing here costs an API call: a
# rebus that doesn't decompose is unsolvable, and a room can't tell "we're
# stupid" from "the game is broken", so the content is curated rather than
# generated and validated at runtime.

import random

REBUS_PIECES = ${py(REBUS_PIECES)}

REBUS_PUZZLES = ${py(REBUS_PUZZLES)}


def resolve_rebus(puzzle):
    """Resolve a puzzle's piece keys into renderable pieces.

    Raises on an unknown key rather than rendering a gap — a rebus missing a
    piece is unsolvable, and the tests call this over every puzzle so a bad key
    cannot ship.
    """
    out = []
    for key in puzzle["pieces"]:
        piece = REBUS_PIECES.get(key)
        if not piece:
            raise KeyError(f'Unknown rebus piece: "{key}" (in "{puzzle["answer"]}")')
        out.append({"key": key, "emoji": piece["emoji"], "reads": piece["reads"]})
    return out


def pick_rebus_puzzle(used_answers=None):
    """Pick a puzzle nobody in this game has seen yet. \`used_answers\` is the
    game's own record, so a single game never repeats one; across games the bank
    recycles freely."""
    used_answers = used_answers or []
    fresh = [p for p in REBUS_PUZZLES if p["answer"] not in used_answers]
    return random.choice(fresh or REBUS_PUZZLES)
`;

fs.writeFileSync(OUT, header);
console.log(
  `wrote ${path.relative(root, OUT)} — ` +
  `${Object.keys(REBUS_PIECES).length} pieces, ${REBUS_PUZZLES.length} puzzles`
);
