// Generates lib/difficultyColors.js — the green ramp the question text is
// printed in, one step per wager tier.
//
// Run: node scripts/build-difficulty-colors.mjs
//
// WHY THIS IS GENERATED RATHER THAN PICKED BY EYE. The question is the single
// most important thing on the screen, and this ramp is the one design element
// that trades legibility for information. Eyeballing five greens on a slate
// ground produces a bottom step nobody can read — the reference spectrum that
// prompted this runs to #26501A, which against #2F4459 is about 1.2:1, i.e.
// invisible. So the ramp is solved to measured contrast targets instead, the
// same discipline CLAUDE.md item 40 applied to the player colours.
//
// The design constraint, stated as a rule: EVERY step must clear 4.5:1 on the
// ground (WCAG AA for body text). That is what makes "darkest = hardest"
// possible at all — the ramp runs from pale mint down to a deep sage, not down
// to black, so "dark" here means "deepest green that is still comfortably
// readable" rather than "dark".

import { writeFileSync } from 'fs';

const GROUND = '#2F4459'; // slate.DEFAULT — ground and plate are one token

// Contrast targets, easiest → hardest. The top matches slate.text (8.99:1,
// AAA) so an easy question reads exactly as bright as ordinary body copy; the
// bottom sits on the AA floor. Five steps, one per wager tier.
const TARGETS = [8.6, 7.4, 6.2, 5.3, 4.5];

// Hue held constant so the ramp reads as one colour deepening, not as five
// different greens. Saturation climbs slightly as it darkens — a pale tint
// needs less chroma to read as green than a deep one does.
const HUE = 132;
const SAT = [0.28, 0.34, 0.40, 0.46, 0.52];

function hslToRgb(h, s, l) {
  const c = (1 - Math.abs(2 * l - 1)) * s;
  const x = c * (1 - Math.abs(((h / 60) % 2) - 1));
  const m = l - c / 2;
  const [r, g, b] =
    h < 60 ? [c, x, 0] :
    h < 120 ? [x, c, 0] :
    h < 180 ? [0, c, x] :
    h < 240 ? [0, x, c] :
    h < 300 ? [x, 0, c] : [c, 0, x];
  return [r + m, g + m, b + m].map((v) => Math.round(v * 255));
}

function toHex([r, g, b]) {
  return '#' + [r, g, b].map((v) => v.toString(16).padStart(2, '0')).join('');
}

function hexToRgb(hex) {
  return [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16));
}

function relativeLuminance([r, g, b]) {
  const [R, G, B] = [r, g, b].map((v) => {
    const s = v / 255;
    return s <= 0.03928 ? s / 12.92 : ((s + 0.055) / 1.055) ** 2.4;
  });
  return 0.2126 * R + 0.7152 * G + 0.0722 * B;
}

function contrast(hexA, hexB) {
  const a = relativeLuminance(hexToRgb(hexA));
  const b = relativeLuminance(hexToRgb(hexB));
  const [hi, lo] = a > b ? [a, b] : [b, a];
  return (hi + 0.05) / (lo + 0.05);
}

// Binary-search lightness for the contrast target. Lightness is the only free
// variable — hue and saturation are fixed above so the ramp stays one colour.
function solve(target, sat) {
  let lo = 0.2;
  let hi = 0.98;
  let best = null;
  for (let i = 0; i < 40; i++) {
    const mid = (lo + hi) / 2;
    const hex = toHex(hslToRgb(HUE, sat, mid));
    const ratio = contrast(hex, GROUND);
    best = { hex, ratio, lightness: mid };
    if (ratio < target) lo = mid;
    else hi = mid;
  }
  return best;
}

const steps = TARGETS.map((target, i) => {
  const { hex, ratio } = solve(target, SAT[i]);
  return { hex, ratio: Number(ratio.toFixed(2)), target };
});

const failures = steps.filter((s) => s.ratio < 4.5);
if (failures.length > 0) {
  console.error('REFUSING TO WRITE: a step fell below AA on the ground.', failures);
  process.exit(1);
}

const body = `// GENERATED by scripts/build-difficulty-colors.mjs — do not edit by hand.
//
// The question text colour, one step per wager tier. A higher wager really
// does produce a harder question (lib/coherence.js turns the wager into the
// difficulty instruction in the generation prompt AND into the fact-bank
// filter), so this colour reports something true rather than decorating.
//
// Lightest green = easiest = smallest wager. Deepest = hardest = biggest.
//
// EVERY step clears 4.5:1 on the slate ground — measured, not assumed. The
// ramp deepens toward sage rather than toward black precisely so the hardest
// question is still the most readable thing on screen. If these ever need
// re-tuning, change the targets in the generator and re-run it; do not hand-
// edit a hex here, because the whole point is that the contrast is proven.
//
// Ground: ${GROUND}
${steps.map((s, i) => `//   tier ${i}: ${s.hex}  ${s.ratio}:1`).join('\n')}

export const DIFFICULTY_COLORS = [
${steps.map((s) => `  '${s.hex}',`).join('\n')}
];

// Contrast of each step against the slate ground, kept alongside the colours
// so a future change can be checked without re-deriving it.
export const DIFFICULTY_CONTRAST = [${steps.map((s) => s.ratio).join(', ')}];

// Safe for any tier index, including a wager that somehow fell outside the
// ladder (Double Down doubles past the top tier).
export function difficultyColor(tierIndex) {
  const i = Math.max(0, Math.min(DIFFICULTY_COLORS.length - 1, tierIndex ?? 0));
  return DIFFICULTY_COLORS[i];
}
`;

writeFileSync(new URL('../lib/difficultyColors.js', import.meta.url), body);
console.log(`Ground ${GROUND}`);
for (const [i, s] of steps.entries()) {
  console.log(`  tier ${i}  ${s.hex}  ${s.ratio}:1  (target ${s.target})`);
}
console.log('\nWrote lib/difficultyColors.js');
